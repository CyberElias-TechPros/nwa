/**
 * Build script for @nwa/design-tokens.
 *
 * Reads tokens.json and emits:
 *   - dist/tokens.css     — CSS custom properties for web (light by default, [data-theme="dark"] + prefers-color-scheme dark overrides).
 *   - dist/tokens.g.css   — generated tokens for Android (Colors.kt).
 *
 * Tokens are the source of truth. Consumers MUST NOT hardcode hex colors.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens.json'), 'utf8'));

mkdirSync(resolve(root, 'dist'), { recursive: true });

const toCssVar = (segment, key) =>
  `--nwa-${segment}-${key.replace(/([A-Z])/g, '-$1').toLowerCase()}`;

const light = [];
const dark = [];
for (const [name, v] of Object.entries(tokens.color)) {
  light.push(`  ${toCssVar('color', name)}: ${v.light};`);
  dark.push(`  ${toCssVar('color', name)}: ${v.dark};`);
}

const spaces = tokens.space.map((px, i) => `  --nwa-space-${i}: ${px}px;`).join('\n');

const radii = Object.entries(tokens.radius)
  .map(([k, v]) => `  --nwa-radius-${k}: ${v}px;`)
  .join('\n');

// Typography: each entry has size + lineHeight (+ optional weight/letterSpacing).
const typeVars = Object.entries(tokens.type).flatMap(([name, t]) => {
  const out = [
    `  --nwa-type-${name}-size: ${t.size}px;`,
    `  --nwa-type-${name}-lh: ${t.lineHeight}px;`,
  ];
  if (t.weight != null) out.push(`  --nwa-type-${name}-weight: ${t.weight};`);
  if (t.letterSpacing != null) out.push(`  --nwa-type-${name}-ls: ${t.letterSpacing}px;`);
  return out;
}).join('\n');

const bps = Object.entries(tokens.breakpoint)
  .map(([k, v]) => `  --nwa-bp-${k}: ${v}px;`)
  .join('\n');

const fonts = Object.entries(tokens.font)
  .map(([k, v]) => `  --nwa-font-${k}: ${v};`)
  .join('\n');

const motions = Object.entries(tokens.motion)
  .map(([k, v]) => `  --nwa-motion-${k}: ${v};`)
  .join('\n');

const css = `/* Auto-generated by scripts/build.js — DO NOT EDIT. */
:root {
${light.join('\n')}
${spaces}
${radii}
${typeVars}
${bps}
${fonts}
${motions}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.join('\n')}
  }
}
:root[data-theme="dark"] {
${dark.join('\n')}
}
`;
writeFileSync(resolve(root, 'dist/tokens.css'), css);

// --- Android: Colors.kt ---
const kt = `// Auto-generated by scripts/build.js — DO NOT EDIT.
package com.naweagree.nwa.design

import androidx.compose.ui.graphics.Color

object NwaColors {
${Object.entries(tokens.color)
  .map(([k, v]) => {
    const name = k.replace(/([A-Z])/g, '_$1').toLowerCase();
    return `    val ${name} = Color(0x${hexToArgb(v.light).toUpperCase()})`;
  })
  .join('\n')}
}
`;
writeFileSync(resolve(root, 'dist/Colors.kt'), kt);

console.log(
  `tokens: ${Object.keys(tokens.color).length} colors, ${tokens.space.length} spaces, ${Object.keys(tokens.radius).length} radii, ${Object.keys(tokens.type).length} type styles → dist/tokens.css, dist/Colors.kt`,
);

function hexToArgb(hex) {
  let h = hex.replace('#', '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  if (h.length !== 6) return 'FF000000';
  return `ff${h.toLowerCase()}`;
}
